# Inventory Management System
This Excel project was created to manage inventory data, track stock levels, and calculate inventory value using Excel formulas and spreadsheet tools.

## Project Overview
The spreadsheet simulates a small business inventory management system. It tracks products, stock quantity, pricing, inventory value, and stock availability.

## Tasks Completed
- Created an inventory tracking dataset
- Calculated total inventory value
- Used IF formulas to generate stock status
- Identified low stock items
- Applied conditional formatting
- Used sorting and filtering tools
- Created an inventory summary section
- Organized and formatted the spreadsheet professionally

## Skills Used
- Excel formulas
- IF statements
- Conditional formatting
- Data organization
- Sorting and filtering
- Inventory calculations
- Spreadsheet formatting

